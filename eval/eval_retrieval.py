def matches(source, accepted):
    return any(source.startswith(a + " ") or source == a for a in accepted)


def main():
    hit1 = hit3 = 0
    reciprocal = 0.0
    for question, accepted in QUESTIONS:
        sources = [h["source"] for h in rag.search(question, k=3)]
        rank = next((i + 1 for i, s in enumerate(sources) if matches(s, accepted)), None)
        hit1 += rank == 1
        hit3 += rank is not None
        reciprocal += 1 / rank if rank else 0
        if rank != 1:
            print(f"rank={rank}  {question}\n         got: {sources}")
    n = len(QUESTIONS)
    print(f"\n{n} questions | hit@1 = {hit1 / n:.0%} | hit@3 = {hit3 / n:.0%} | MRR = {reciprocal / n:.2f}")


if __name__ == "__main__":
    main()
