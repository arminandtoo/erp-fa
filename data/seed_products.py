def seed(db_path=DB_PATH):
    conn = sqlite3.connect(db_path)
    conn.executescript("""
        DROP TABLE IF EXISTS products;
        DROP TABLE IF EXISTS product_categories;
        CREATE TABLE product_categories (
            id   INTEGER PRIMARY KEY AUTOINCREMENT,
            code TEXT UNIQUE NOT NULL,
            name TEXT NOT NULL
        );
        CREATE TABLE products (
            id                   INTEGER PRIMARY KEY AUTOINCREMENT,
            sku                  TEXT UNIQUE NOT NULL,
            name                 TEXT NOT NULL,
            category_id          INTEGER NOT NULL REFERENCES product_categories(id),
            brand                TEXT,
            package_size         REAL NOT NULL CHECK (package_size > 0),
            package_unit         TEXT NOT NULL,
            price                INTEGER NOT NULL CHECK (price > 0),
            stock                INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
            dose_soil_g_per_kg   REAL,
            dose_hectare         REAL,
            dose_hectare_unit    TEXT,
            dose_spray_per_1000l REAL,
            phi_days             INTEGER,
            suitable_crops       TEXT,
            description          TEXT,
            is_active            INTEGER NOT NULL DEFAULT 1,
            updated_at           TEXT DEFAULT CURRENT_TIMESTAMP
        );
    """)
    conn.executemany("INSERT INTO product_categories (code, name) VALUES (?, ?)", CATEGORIES.items())
    cat_ids = dict(conn.execute("SELECT code, id FROM product_categories"))
    conn.executemany(
        """INSERT INTO products (sku, name, category_id, brand, package_size, package_unit, price, stock,
               dose_soil_g_per_kg, dose_hectare, dose_hectare_unit, dose_spray_per_1000l, phi_days,
               suitable_crops, description)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
        [(p[0], p[1], cat_ids[p[2]], *p[3:]) for p in PRODUCTS],
    )
    conn.commit()
    conn.close()


if __name__ == "__main__":
    seed()
    conn = sqlite3.connect(DB_PATH)
    assert conn.execute("SELECT COUNT(*) FROM products").fetchone()[0] == len(PRODUCTS)
    assert conn.execute("SELECT COUNT(*) FROM citizens").fetchone()[0] > 0  # جدول‌های قبلی سالم مانده‌اند
    # مثال: یک کیسه ۵۰ کیلویی اوره با دوز ۰.۵ گرم بر کیلو خاک → ۱۰۰٬۰۰۰ کیلو خاک
    size, dose = conn.execute("SELECT package_size, dose_soil_g_per_kg FROM products WHERE sku='F-001'").fetchone()
    assert size * 1000 / dose == 100_000
    print(f"OK: {len(PRODUCTS)} محصول در {DB_PATH} ثبت شد")
